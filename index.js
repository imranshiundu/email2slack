const DEFAULT_MAX_BODY = 700;

export function parseEmail(raw = '') {
  const normalized = String(raw).replace(/\r\n/g, '\n');
  const separator = normalized.indexOf('\n\n');
  const headerText = separator === -1 ? normalized : normalized.slice(0, separator);
  const body = separator === -1 ? '' : normalized.slice(separator + 2).trim();

  const headers = {};
  let currentKey = null;

  for (const line of headerText.split('\n')) {
    if (!line.trim()) continue;
    if (/^[\t ]/.test(line) && currentKey) {
      headers[currentKey] += ` ${line.trim()}`;
      continue;
    }

    const colon = line.indexOf(':');
    if (colon === -1) continue;
    currentKey = line.slice(0, colon).trim().toLowerCase();
    headers[currentKey] = line.slice(colon + 1).trim();
  }

  return { headers, body };
}

export function redactSecrets(text = '') {
  return String(text)
    .replace(/(authorization:\s*bearer\s+)[^\s]+/gi, '$1[REDACTED]')
    .replace(/((api[_-]?key|token|password|secret)\s*[:=]\s*)[^\s,;]+/gi, '$1[REDACTED]')
    .replace(/\b[A-Za-z0-9_\-]{32,}\b/g, '[REDACTED_LONG_TOKEN]');
}

export function classifyEmail(email) {
  const text = `${email.headers.subject || ''}\n${email.body || ''}`.toLowerCase();
  if (/(sev\s*1|sev1|critical|outage|incident|failed|failure|down|breach)/i.test(text)) return 'critical';
  if (/(urgent|warning|attention|invoice|payment|expired|retry|degraded)/i.test(text)) return 'warning';
  return 'info';
}

function levelLabel(level) {
  if (level === 'critical') return { icon: '🚨', label: 'CRITICAL' };
  if (level === 'warning') return { icon: '⚠️', label: 'WARNING' };
  return { icon: '📩', label: 'INFO' };
}

export function toSlackPayload(raw, options = {}) {
  const email = typeof raw === 'string' ? parseEmail(raw) : raw;
  const level = classifyEmail(email);
  const { icon, label } = levelLabel(level);
  const maxBody = Number(options.maxBody || DEFAULT_MAX_BODY);
  const body = options.redact === false ? email.body || '' : redactSecrets(email.body || '');
  const preview = body.slice(0, maxBody) || '(empty email body)';
  const subject = email.headers.subject || 'New email';
  const from = email.headers.from || 'unknown sender';
  const date = email.headers.date || new Date().toISOString();

  const payload = {
    text: `${icon} ${label}: ${subject} from ${from}`,
    blocks: [
      { type: 'header', text: { type: 'plain_text', text: `${icon} ${subject}`.slice(0, 150) } },
      { type: 'section', fields: [
        { type: 'mrkdwn', text: `*From*\n${from}` },
        { type: 'mrkdwn', text: `*Level*\n${label}` },
        { type: 'mrkdwn', text: `*Date*\n${date}` },
        { type: 'mrkdwn', text: `*Message-ID*\n${email.headers['message-id'] || 'not provided'}` },
      ] },
      { type: 'section', text: { type: 'mrkdwn', text: preview } },
      { type: 'context', elements: [{ type: 'mrkdwn', text: 'Generated by email2slack' }] },
    ],
  };

  if (options.channel) payload.channel = options.channel;
  if (options.username) payload.username = options.username;
  return payload;
}

export async function postToSlack(webhookUrl, payload, fetchImpl = fetch) {
  if (!webhookUrl) throw new Error('Missing Slack webhook URL. Pass --webhook or set SLACK_WEBHOOK_URL.');
  const response = await fetchImpl(webhookUrl, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(payload),
  });
  if (!response.ok) throw new Error(`Slack webhook failed with status ${response.status}`);
  return true;
}
